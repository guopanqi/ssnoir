/**
 * 黑水 · 视觉总谱
 *
 * 「黑水」的一句话：城市不是被照亮的，城市是黑夜里几处光源在湿地面与河面上留下的痕迹。
 *
 * 五条互相独立的决定（改任意一条都不需要动别的）：
 *   MASS   体块：建筑是纯黑实体，只有"受光面"被点亮，终止线是硬的。
 *   LINE   描线：不再是全城白线框，而是被光照调制的逆光边——黑块与亮背景的接缝才发光。
 *   LIGHT  光：一冷一暖，各有动机。冷键从城后打（逆光），暖池只落在真的有事的几处。
 *   WET    湿：地面是镜子。反射来自一次真实镜像渲染，按粗糙度纵向拉丝。
 *   AIR    空气与镜头：体积雾里跑真正的灯，加上 halation / 拉丝 / 颗粒 / 暗角。
 *
 * 坐标：与 data/city.json 一致，Three.js Y-up，单位米。Blender(x,y,z) -> three(x,z,-y)。
 */

/**
 * 程序生成的种子。实验室纪律要求"程序生成必须使用可复现 seed"，
 * 所以雨的每一滴都由这个 seed 推出来，不用 Math.random()。
 */
export const SEED = 20261004;

/** mulberry32：小而确定的 PRNG。返回 [0,1)。 */
export function makeRng(seed = SEED) {
  let a = seed >>> 0;
  return function rng() {
    a = (a + 0x6D2B79F5) >>> 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

