import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
const base=fileURLToPath(new URL('../',import.meta.url));
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1100}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
console.log('Browser ready');await page.goto('http://127.0.0.1:5178/baselines.html');console.log('Page loaded');
await page.waitForFunction(()=>window.baselineLab?.player.story);
console.log('App ready');assert.equal(await page.locator('.tabs button').count(),6);
assert.equal(await page.locator('.scenery').innerHTML(),'');
// Execute every command; bypass only time delays and manual dialogue waits.
await page.evaluate(async()=>{const {player,load,stories}=window.baselineLab;player.delay=async()=>{};player.dialogue=async c=>{player.stage.say(c);player.stage.text(c.text);};for(let i=0;i<stories.length;i++){await load(i);if(player.state!=='ended')throw Error(`${stories[i].id}: ${player.error||player.state}`);for(let b=0;b<stories[i].beats.length;b++){await load(i,b);if(player.state!=='ended')throw Error(`${stories[i].id}/${b}: ${player.error||player.state}`);}}});
console.log('Command playback passed');assert.deepEqual(errors,[]);
// Fresh page: real timing, explicit pause, contact composition and narrow layout.
await page.reload();await page.waitForFunction(()=>window.baselineLab?.player.story);
await page.evaluate(()=>{window.baselineLab.load(4,1);});
await page.waitForFunction(()=>window.baselineLab.stage.people.has('搭肩'));
await page.locator('#pause').click();
assert.equal(await page.evaluate(()=>window.baselineLab.player.paused),true);
await page.screenshot({path:`${base}art/baselines/preview-contact.png`});
await page.locator('#captions').uncheck();
assert.equal(await page.locator('.dialogue').evaluate(el=>getComputedStyle(el).visibility),'hidden');
await page.setViewportSize({width:844,height:650});
await page.screenshot({path:`${base}art/baselines/preview-narrow.png`});
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
await page.setViewportSize({width:1440,height:1100});
await page.locator('#captions').check();
await page.evaluate(()=>{window.baselineLab.load(1,1);});
await page.waitForFunction(()=>window.baselineLab.player.waiting);
await page.evaluate(()=>{window.baselineLab.player.advance();window.baselineLab.player.advance();});
await page.waitForFunction(()=>window.baselineLab.stage.props.has('烟盒'));
await page.waitForFunction(()=>window.baselineLab.stage.people.get('夜莺').pose==='低头');
await page.locator('#pause').click();
await page.screenshot({path:`${base}art/baselines/preview-pack.png`});
await page.goto('http://127.0.0.1:5178/');
await page.waitForFunction(()=>window.stageLab?.player.story);
assert.deepEqual(errors,[]);
await browser.close();console.log('PASS: 6 full scenes, all 23 node reconstructions, real-time pause, contact, prop, captions, narrow layout, original entry.');
